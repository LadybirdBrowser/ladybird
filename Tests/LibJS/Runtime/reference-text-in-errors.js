test("references that are longer than what gets looked at", () => {
    const long = "a".repeat(5000);
    expect(new Function(`new '${long}'.nope();`)).toThrow(TypeError);
    expect(new Function(`'${long}'.nope();`)).toThrow(TypeError);
    expect(new Function(`var ${long} = {}; ${long}.nope();`)).toThrow(TypeError);
    expect(new Function(`var ${long}; ${long}.nope = 1;`)).toThrow(TypeError);
    expect(new Function(`[${long}].nope.x = 1; var ${long};`)).toThrow(TypeError);
});

test("source that looks like something else", () => {
    expectMessage("o /* ) */ .nope();", "undefined is not a function (evaluated from 'o.nope')");
    expectMessage("o // )\n  .nope();", "undefined is not a function (evaluated from 'o.nope')");
    expectMessage("o[')'].nope();", `Cannot access property "nope" on undefined object "o[')']"`);
    expectMessage("o[']'].nope();", `Cannot access property "nope" on undefined object "o[']']"`);
});
