ErrorOr<bool> ed25519_verify(ReadonlyBytes public_key, ReadonlyBytes signature, ReadonlyBytes message)
{
    // For Ed25519, reject small-order points for security
    // This is required by RFC 8032 and the Web Crypto API specification
    if (is_small_order_ed25519_point(public_key))
        return false;

    // Also check the R point in the signature (first 32 bytes) for small-order
    if (signature.size() >= 32 && is_small_order_ed25519_point(signature.slice(0, 32)))
        return false;

    auto key = TRY(OpenSSL_PKEY::wrap(EVP_PKEY_new_raw_public_key_ex(nullptr, "ED25519", nullptr, public_key.data(), public_key.size())));
    auto ctx = TRY(OpenSSL_MD_CTX::create());
    OPENSSL_TRY(EVP_DigestVerifyInit_ex(ctx.ptr(), nullptr, nullptr, nullptr, nullptr, key.ptr(), nullptr));

    auto result = EVP_DigestVerify(ctx.ptr(), signature.data(), signature.size(), message.data(), message.size());
    if (result == 1)
        return true;
    if (result == 0)
        return false;
    OPENSSL_TRY(result);
    VERIFY_NOT_REACHED();
}

