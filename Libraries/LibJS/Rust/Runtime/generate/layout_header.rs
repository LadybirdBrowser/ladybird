    w.define_hex("OBJECT_FLAG_IS_DIRECT_GETTER_FUNCTION", object_flag::IS_DIRECT_GETTER_FUNCTION.into());
    w.define_hex("OBJECT_FLAG_IS_GLOBAL_OBJECT", object_flag::IS_GLOBAL_OBJECT.into());
    w.define_hex("OBJECT_FLAG_HAS_UNIMPLEMENTED_PROPERTIES", object_flag::HAS_UNIMPLEMENTED_PROPERTIES.into());
    w.define_hex("OBJECT_FLAG_IS_HTMLDDA", object_flag::IS_HTMLDDA.into());

