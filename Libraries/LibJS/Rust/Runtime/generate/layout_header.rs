/// The imports the static assertions need to name the same types as the header.
const STATIC_ASSERTIONS_PREAMBLE: &str = "\
use crate::layout::cell::*;
use crate::layout::class::*;
use crate::layout::execution_context::*;
use crate::layout::host_object::*;
use crate::layout::object::*;
use crate::layout::realm::*;
use crate::layout::shape::*;
use crate::layout::vm::*;

const fn size_of_field<Struct, Field>(_: fn(&Struct) -> *const Field) -> usize {
    size_of::<Field>()
}
";

const PREAMBLE: &str = "\
/*
 * Copyright (c) 2026-present, the Ladybird developers.
 *
 * SPDX-License-Identifier: BSD-2-Clause
 */

// Generated by the libjs_runtime_rust build script from its layout module -- DO NOT EDIT
//
// The offsets, sizes and constants of the runtime's structures that an embedder reads or writes directly.

#ifndef LIBJS_EMBEDDING_LAYOUT_H
#define LIBJS_EMBEDDING_LAYOUT_H

#include <LibJS/HostObjectABI.h>
";

/// The start of the header's C++ section, which checks the layout module's mirror of LibJS/HostObjectABI.h against
/// that header.
const HOST_OBJECT_ABI_CHECKS_PREAMBLE: &str = "\
#ifdef __cplusplus
#    include <type_traits>
#    include <utility>

// The runtime mirrors LibJS/HostObjectABI.h in src/layout/host_class.rs and src/layout/host_object.rs. These check the
// size, alignment, field count and the offset and type of every field of that mirror, and the value of every constant
// it defines, against the header.
namespace JSEmbeddingLayoutChecks {

struct InitializerOfAnyField {
    template<typename Field>
    operator Field() const;
};

template<size_t>
using InitializerOfAnyFieldAt = InitializerOfAnyField;

template<typename Aggregate, size_t... field_indices>
consteval bool initializes_from_initializers(std::index_sequence<field_indices...>)
{
    return requires { Aggregate { InitializerOfAnyFieldAt<field_indices> {}... }; };
}

// Aggregate initialization takes one initializer per field and no more, which also counts fields that fit in padding.
template<typename Aggregate, size_t field_count>
constexpr bool has_exactly_fields = initializes_from_initializers<Aggregate>(std::make_index_sequence<field_count> {})
    && !initializes_from_initializers<Aggregate>(std::make_index_sequence<field_count + 1> {});

}

";

pub struct LayoutHeader {
    pub text: String,
    pub static_assertions: String,
}

struct HeaderWriter {
    definitions: String,
    defined_names: HashSet<String>,
    host_object_abi_checks: String,
    static_assertions: String,
}

impl HeaderWriter {
    fn new() -> Self {
        Self {
            definitions: String::new(),
            defined_names: HashSet::new(),
            host_object_abi_checks: String::new(),
            static_assertions: STATIC_ASSERTIONS_PREAMBLE.to_string(),
        }
    }

    fn section(&mut self, title: &str) {
        let _ = write!(self.definitions, "\n// {title}\n");
    }

    fn define(&mut self, name: &str, value: impl Display) {
        assert!(
            self.defined_names.insert(name.to_string()),
            "JS_LAYOUT_{name} is defined twice"
        );
        let _ = writeln!(self.definitions, "#define JS_LAYOUT_{name} {value}");
    }

    fn define_hex(&mut self, name: &str, value: u64) {
        self.define(name, format!("0x{value:X}"));
    }

    fn assert_offset(&mut self, type_path: &str, field_path: &str, offset: usize) {
        let _ = writeln!(
            self.static_assertions,
            "const _: () = assert!(core::mem::offset_of!({type_path}, {field_path}) == {offset});"
        );
    }

    fn assert_size(&mut self, type_path: &str, size: usize) {
        let _ = writeln!(
            self.static_assertions,
            "const _: () = assert!(size_of::<{type_path}>() == {size});"
        );
    }

    fn assert_field_size(&mut self, type_path: &str, field_path: &str, size: usize) {
        let _ = writeln!(
            self.static_assertions,
            "const _: () = assert!(size_of_field(|value: &{type_path}| &raw const value.{field_path}) == {size});"
        );
    }

    fn check_host_object_abi(&mut self, condition: &str) {
        let _ = writeln!(self.host_object_abi_checks, "static_assert({condition});");
    }

    fn finish(self) -> LayoutHeader {
        let mut text = String::from(PREAMBLE);
        text.push_str(&self.definitions);
        text.push('\n');
        text.push_str(HOST_OBJECT_ABI_CHECKS_PREAMBLE);
        text.push_str(&self.host_object_abi_checks);
        text.push_str("#endif\n\n#endif // LIBJS_EMBEDDING_LAYOUT_H\n");
        LayoutHeader {
            text,
            static_assertions: self.static_assertions,
        }
    }
}

/// Takes a raw pointer to the field, since a field of a packed struct such as CellHeader cannot have a reference.
fn size_of_field<Struct, Field>(_: fn(&Struct) -> *const Field) -> usize {
    size_of::<Field>()
}

/// Defines the offset of a field and its size, which tells an embedder the width to read it at.
macro_rules! offset {
    ($writer:expr, $name:expr, $type:ident, $($field:tt)+) => {{
        let name = $name;
        let offset = offset_of!($type, $($field)+);
        $writer.define(&format!("{name}_OFFSET"), offset);
        $writer.assert_offset(stringify!($type), stringify!($($field)+), offset);
        let size = size_of_field(|value: &$type| &raw const value.$($field)+);
        $writer.define(&format!("{name}_SIZE"), size);
        $writer.assert_field_size(stringify!($type), stringify!($($field)+), size);
    }};
}

macro_rules! size {
    ($writer:expr, $name:expr, $type:ident) => {{
        let size = size_of::<$type>();
        $writer.define(&format!("{}_SIZE", $name), size);
        $writer.assert_size(stringify!($type), size);
    }};
}

/// Defines the offset of each listed field. The list has to name every field of the struct, so that one added to it
/// fails to compile here until the header has it too.
macro_rules! every_field_offset {
    ($writer:expr, $prefix:literal, $type:ident { $($field:ident),* $(,)? }) => {{
        const _: fn(&$type) = |value| {
            let $type { $($field: _),* } = value;
        };
        $(offset!($writer, format!("{}_{}", $prefix, stringify!($field).to_uppercase()), $type, $field);)*
    }};
}

/// Checks the size, alignment, field count and the offset and type of every field of a struct that mirrors one of
/// LibJS/HostObjectABI.h.
macro_rules! check_host_object_abi_struct {
    ($writer:expr, $type:ident { $($field:ident),* $(,)? }) => {{
        const _: fn(&$type) = |value| {
            let $type { $($field: _),* } = value;
        };
        let type_name = stringify!($type);
        $writer.check_host_object_abi(&format!("sizeof({type_name}) == {}", size_of::<$type>()));
        $writer.check_host_object_abi(&format!("alignof({type_name}) == {}", align_of::<$type>()));
        let field_count = [$(stringify!($field)),*].len();
        $writer.check_host_object_abi(&format!(
            "JSEmbeddingLayoutChecks::has_exactly_fields<{type_name}, {field_count}>"
        ));
        $(
            let field_name = stringify!($field).trim_start_matches("r#");
            $writer.check_host_object_abi(&format!(
                "offsetof({type_name}, {field_name}) == {}",
                offset_of!($type, $field)
            ));
            $writer.check_host_object_abi(&format!(
                "std::is_same_v<decltype({type_name}::{field_name}), {}>",
                c_type_spelling_of_field(|value: &$type| &value.$field)
            ));
        )*
    }};
}

macro_rules! check_host_object_abi_constants {
    ($writer:expr, $($name:ident),* $(,)?) => {
        $($writer.check_host_object_abi(&format!("{} == {}", stringify!($name), $name));)*
    };
}

/// The C layout that #[repr(C, u8)] gives ScriptOrModule: the tag, then the payload of the variant.
#[repr(C)]
struct ScriptOrModuleRepresentation {
    tag: u8,
    payload: usize,
}

/// Spells a class name such as RawJSONObject the way C spells constants, RAW_JSON_OBJECT.
fn screaming_snake_case(name: &str) -> String {
    let characters: Vec<char> = name.chars().collect();
    let mut result = String::new();
    for (index, &character) in characters.iter().enumerate() {
        if index > 0 && character.is_ascii_uppercase() {
            let previous = characters[index - 1];
            let next_is_lowercase = characters.get(index + 1).is_some_and(char::is_ascii_lowercase);
            if previous.is_ascii_lowercase()
                || previous.is_ascii_digit()
                || (previous.is_ascii_uppercase() && next_is_lowercase)
            {
                result.push('_');
            }
        }
        result.push(character.to_ascii_uppercase());
    }
    result
}

fn cell_kind_name(kind: CellKind) -> &'static str {
    match kind {
        CellKind::Other => "OTHER",
        CellKind::Object => "OBJECT",
        CellKind::PrimitiveString => "PRIMITIVE_STRING",
        CellKind::Symbol => "SYMBOL",
        CellKind::BigInt => "BIG_INT",
        CellKind::Accessor => "ACCESSOR",
    }
}

