//! Writes LibJS/Embedding/Layout.h: the offsets, sizes and constants of the runtime's structures that an embedder
//! reads or writes directly, computed from the crate's layout module the same way as the interpreter's layout. Every
//! offset and size is also written out as a static assertion that the crate compiles. The header's C++ section checks
//! the size, alignment, field count and the offset and type of every field of the layout module's mirror of
//! LibJS/HostObjectABI.h, and the value of every constant the mirror defines, against that header. A constant that
//! only the header defines goes unnoticed.

