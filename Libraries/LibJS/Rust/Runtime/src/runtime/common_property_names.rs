use ak::Utf16FlyString;

use crate::runtime::property_key::{PropertyKey, StringMayBeNumber};

/// Defines CommonPropertyNames with one key per name. A name is its own string unless it is followed by `= "string"`,
/// for the strings that are not valid identifiers as they are.
macro_rules! define_common_property_names {
    (@string $name:ident) => {
        stringify!($name)
    };
    (@string $name:ident $string:literal) => {
        $string
    };
    ($($name:ident $(= $string:literal)?,)*) => {
        /// The property names the runtime uses, interned once per VM.
        #[allow(non_snake_case)]
        pub struct CommonPropertyNames {
            $(pub $name: PropertyKey,)*
        }

        impl CommonPropertyNames {
            pub fn new() -> Self {
                Self {
                    $($name: common_property_name(define_common_property_names!(@string $name $($string)?)),)*
                }
            }
        }
    };
}

fn common_property_name(name: &str) -> PropertyKey {
    PropertyKey::from_fly_string(Utf16FlyString::from_utf8(name), StringMayBeNumber::No)
}

impl Default for CommonPropertyNames {
    fn default() -> Self {
        Self::new()
    }
}

